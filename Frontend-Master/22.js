[a] = [2, 3, 4, 5];

console.log(a); // Output: 2

// ✋✋ Explaination :
// here we are using array destructuring to assign the first element of the array `[2, 3, 4, 5]` to the variable `a`. The variable `a` will hold the value `2`, which is the first element of the array. When we log `a`, it outputs `2`. This demonstrates how array destructuring can be used to extract values from an array and assign them to variables.✋✋